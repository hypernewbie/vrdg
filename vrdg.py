import os, sys, glob, hashlib, json

# ------------------------------------------------ Config & Globals -------------------------------------------------------------

CURTASK_SOURCE = ""
CURTASK_LOCATION = ""
CURTASK_NAME = ""
CURTASK_TYPE = "graphics"
CURTASK_IO = []
CURTASK_CREATE = []
CURTASK_LIFETIME = {}
CURTASK_CPU_PROFILE = ""
CURTASK_GPU_PROFILE = ""
CURTASK_FUNC = ""
CURTASK_OPEN = False

GPU_PROFILE_ENTRIES = []
TASK_SOURCES = {}
GPU_PROFILE_SOURCES = {}

OUTPUT_FILE_BUFFER = [
    "// This file is generated by %s. DO NOT EDIT!!!\n\n"
    % os.path.basename(sys.argv[0]),
    "#pragma once\nnamespace vrdg {\n",
]

IOTYPE_TO_FUNCTIONARG = {}
IOTYPE_TO_FUNCTIONARG["Write_Buffer"] = "Buffer"
IOTYPE_TO_FUNCTIONARG["Read_Buffer"] = "Buffer"
IOTYPE_TO_FUNCTIONARG["Write_TextureFB"] = "FrameBuffer"
IOTYPE_TO_FUNCTIONARG["Read_TextureFB"] = "FrameBuffer"
IOTYPE_TO_FUNCTIONARG["Create_Buffer"] = "Buffer&"
IOTYPE_TO_FUNCTIONARG["Create_TextureFB"] = "FrameBuffer&"

IOTYPE_TO_ENGINE_FUNCTIONARG = {}
IOTYPE_TO_ENGINE_FUNCTIONARG["Write_Buffer"] = "VRDG_BUFFER"
IOTYPE_TO_ENGINE_FUNCTIONARG["Read_Buffer"] = "VRDG_BUFFER"
IOTYPE_TO_ENGINE_FUNCTIONARG["Write_TextureFB"] = "VRDG_FRAMEBUFFER"
IOTYPE_TO_ENGINE_FUNCTIONARG["Read_TextureFB"] = "VRDG_FRAMEBUFFER"
IOTYPE_TO_ENGINE_FUNCTIONARG["Create_Buffer"] = "VRDG_BUFFER"
IOTYPE_TO_ENGINE_FUNCTIONARG["Create_TextureFB"] = "VRDG_FRAMEBUFFER"

IOTYPE_TO_ATTACH = {}
IOTYPE_TO_ATTACH["Write_Buffer"] = "VRDG_TYPE_BUFFER"
IOTYPE_TO_ATTACH["Read_Buffer"] = "VRDG_TYPE_BUFFER"
IOTYPE_TO_ATTACH["Write_TextureFB"] = "VRDG_TYPE_FB"
IOTYPE_TO_ATTACH["Read_TextureFB"] = "VRDG_TYPE_FB"
IOTYPE_TO_ATTACH["Create_Buffer"] = "VRDG_TYPE_BUFFER"
IOTYPE_TO_ATTACH["Create_TextureFB"] = "VRDG_TYPE_FB"

for suffix in ("Buffer", "TextureFB"):
    t = "ReadWrite_" + suffix
    IOTYPE_TO_FUNCTIONARG[t] = IOTYPE_TO_FUNCTIONARG["Read_" + suffix]
    IOTYPE_TO_ENGINE_FUNCTIONARG[t] = IOTYPE_TO_ENGINE_FUNCTIONARG["Read_" + suffix]
    IOTYPE_TO_ATTACH[t] = IOTYPE_TO_ATTACH["Read_" + suffix]

ACCESS_ROLES = {
    "Color": ("TextureFB", ("Write", "ReadWrite"), "graphics"),
    "Depth": ("TextureFB", ("Read", "Write", "ReadWrite"), "graphics"),
    "Sampled": ("TextureFB", ("Read",), None),
    "Storage": (None, ("Read", "Write", "ReadWrite"), None),
    "Copy": (None, ("Read", "Write"), None),
    "Indirect": ("Buffer", ("Read",), None),
}

# ---------------------------------------------------- Helper functions ----------------------------------------------------------


def _extract_args_segment(line):
    start = line.find("(")
    if start == -1:
        return ""

    depth = 0
    for i in range(start, len(line)):
        ch = line[i]
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
            if depth == 0:
                if line[i + 1 :].strip():
                    raise ValueError("unexpected text after closing parenthesis")
                return line[start + 1 : i]

    raise ValueError("missing closing parenthesis")


def _split_args(segment):
    args = []
    buf = []
    depth = 0
    for ch in segment:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1

        if ch == "," and depth == 0:
            args.append("".join(buf).strip())
            buf = []
            continue

        buf.append(ch)

    tail = "".join(buf).strip()
    if tail or segment.strip():
        args.append(tail)

    return args


def getLineArguments(line):
    segment = _extract_args_segment(line)
    if not segment:
        return []
    return _split_args(segment)


def _abort(fileName, lineIndex, msg):
    where = "%s:%d" % (fileName, lineIndex) if lineIndex >= 0 else fileName
    task = "task '%s': " % CURTASK_NAME if CURTASK_OPEN else ""
    print("%s: error: %s%s" % (where, task, msg), file=sys.stderr)
    sys.exit(1)


def generateTimerIdFromName(name):
    hash_bytes = hashlib.sha256(name.encode("utf-8")).digest()
    timer_id = int.from_bytes(hash_bytes[:8], byteorder="little")
    return timer_id


# -------------------------------------------------- Render Graph Codegen -----------------------------------------------------------


def getSeparator(args):
    if len(args) > 0:
        return ", "
    return ""


def getAccessFlags(t, args):
    flags = ["VRDG_READ"] if t.startswith("Read_") else ["VRDG_WRITE"]
    if t.startswith("ReadWrite_"):
        flags.insert(0, "VRDG_READ")
    if "Discard" in args:
        flags.append("VRDG_DISCARD")
    flags.extend("VRDG_" + role.upper() for role in ACCESS_ROLES if role in args)
    return " | ".join(flags)


def getAccessError(t, args):
    access, suffix = t.split("_", 1)
    roles = [role for role in ACCESS_ROLES if role in args]
    if "Discard" in args and access != "Write":
        return "Discard is only valid on Write_* accesses"
    for role in roles:
        expectedType, operations, taskType = ACCESS_ROLES[role]
        if (expectedType and expectedType != suffix) or access not in operations or (taskType and taskType != CURTASK_TYPE):
            return "invalid access role '%s' for %s in a %s task" % (role, t, CURTASK_TYPE)
    if access != "Read" and len(roles) > 1:
        return "conflicting access roles"
    return None


def generateCurrentTask():
    callArgs = []
    inputArgs = []
    inputEngineArgs = []
    for t, name, args in CURTASK_IO:
        inputArgs.append(IOTYPE_TO_FUNCTIONARG[t] + " " + name)
        inputEngineArgs.append(IOTYPE_TO_ENGINE_FUNCTIONARG[t] + " " + name)
        callArgs.append(name)
    for t, name, args in CURTASK_CREATE:
        inputArgs.append(IOTYPE_TO_FUNCTIONARG[t] + " " + name)

    if len(CURTASK_FUNC) > 0:
        OUTPUT_FILE_BUFFER.append("// %s" % CURTASK_SOURCE)
        OUTPUT_FILE_BUFFER.append(
            "void %s( %s );" % (CURTASK_FUNC, ", ".join(inputEngineArgs))
        )
        OUTPUT_FILE_BUFFER.append("\n")

    OUTPUT_FILE_BUFFER.append("// %s" % CURTASK_SOURCE)
    OUTPUT_FILE_BUFFER.append(
        "void %s_CallbackBody( State* state, EngineInterface* ei, Task* task )"
        % CURTASK_NAME
    )
    OUTPUT_FILE_BUFFER.append("{")
    if len(CURTASK_CPU_PROFILE) > 0:
        OUTPUT_FILE_BUFFER.append(
            '    MICROPROFILE_SCOPEI( "vrdg", "%s", 0xFFFFFFFF );' % CURTASK_CPU_PROFILE
        )
    if len(CURTASK_GPU_PROFILE) > 0:
        timerId = generateTimerIdFromName(CURTASK_GPU_PROFILE)
        OUTPUT_FILE_BUFFER.append("    VRDG_GPU_PROFILE_BEGIN( %dULL );" % timerId)
        GPU_PROFILE_ENTRIES.append((CURTASK_GPU_PROFILE, timerId))

    if len(CURTASK_FUNC) > 0:
        for i, (t, name, args) in enumerate(CURTASK_IO):
            getter = "GetEngineBufferObject" if IOTYPE_TO_ATTACH[t] == "VRDG_TYPE_BUFFER" else "GetEngineFBObject"
            OUTPUT_FILE_BUFFER.append(
                "    auto %s = ei->%s( task->uses[%d].id );" % (name, getter, i)
            )
        OUTPUT_FILE_BUFFER.append("    %s( %s );" % (CURTASK_FUNC, ", ".join(callArgs)))
    if len(CURTASK_GPU_PROFILE) > 0:
        OUTPUT_FILE_BUFFER.append("    VRDG_GPU_PROFILE_END( %dULL );" % timerId)
    OUTPUT_FILE_BUFFER.append("}\n")

    OUTPUT_FILE_BUFFER.append("// %s" % CURTASK_SOURCE)
    OUTPUT_FILE_BUFFER.append(
        "void %s( State* s%s%s )" % (CURTASK_NAME, getSeparator(inputArgs), ", ".join(inputArgs))
    )
    OUTPUT_FILE_BUFFER.append("{")
    OUTPUT_FILE_BUFFER.append("    Task task;")
    OUTPUT_FILE_BUFFER.append('    task.name = "%s";' % CURTASK_NAME)
    OUTPUT_FILE_BUFFER.append("    task.source = %s;\n" % json.dumps(CURTASK_LOCATION, ensure_ascii=False))
    for t, name, args in CURTASK_IO:
        OUTPUT_FILE_BUFFER.append(
            "    task.uses.push_back( { %s, %s, %s } );" % (name, IOTYPE_TO_ATTACH[t], getAccessFlags(t, args))
        )
    for t, name, args in CURTASK_CREATE:
        OUTPUT_FILE_BUFFER.append("    %s = s->resources.size();" % name)
        OUTPUT_FILE_BUFFER.append("    {")
        OUTPUT_FILE_BUFFER.append("        Resource resource;")
        OUTPUT_FILE_BUFFER.append("        resource.id = %s;" % name)
        OUTPUT_FILE_BUFFER.append('        resource.name = "%s";' % name)
        OUTPUT_FILE_BUFFER.append("        resource.type = %s;" % IOTYPE_TO_ATTACH[t])
        OUTPUT_FILE_BUFFER.append("        resource.lifetime = VRDG_%s;" % CURTASK_LIFETIME.get(name, "Transient").upper())
        OUTPUT_FILE_BUFFER.append("        resource.declarationTask = ( int ) s->tasks.size();")
        OUTPUT_FILE_BUFFER.append("        resource.resolveDescriptor = []( State* state, EngineInterface* ei, Task* task, Resource* resource ) {")
        field, desc = ("buffer", "BufferDesc") if t == "Create_Buffer" else ("fb", "FBDesc")
        OUTPUT_FILE_BUFFER.append("            resource->%s = %s( %s );" % (field, desc, ", ".join(args)))
        OUTPUT_FILE_BUFFER.append("        };")
        OUTPUT_FILE_BUFFER.append("        s->resources.push_back( resource );")
        OUTPUT_FILE_BUFFER.append("    }")
    OUTPUT_FILE_BUFFER.append("    task.callback = %s_CallbackBody;" % CURTASK_NAME)
    OUTPUT_FILE_BUFFER.append("    task.flags = %s;" % ("VRDG_GRAPHICS" if CURTASK_TYPE == "graphics" else "VRDG_COMPUTE"))
    OUTPUT_FILE_BUFFER.append("    s->tasks.push_back( task );")
    OUTPUT_FILE_BUFFER.append("}\n")


def parseSourceFile(fileName):
    global CURTASK_SOURCE
    global CURTASK_LOCATION
    global CURTASK_NAME
    global CURTASK_TYPE
    global CURTASK_IO
    global CURTASK_CREATE
    global CURTASK_LIFETIME
    global CURTASK_CPU_PROFILE
    global CURTASK_GPU_PROFILE
    global CURTASK_FUNC
    global CURTASK_OPEN

    fp = open(fileName, "r", encoding="utf-8", errors="ignore")

    def abort(message):
        _abort(fileName, lineIndex, "%s [%s]" % (message, line))

    for lineIndex, line in enumerate(fp, 1):
        if line.startswith("///>") == False:
            continue

        line = line[4:].strip()
        if not line:
            continue
        try:
            lineArgs = getLineArguments(line)
        except ValueError as error:
            abort(str(error))
        directive = line.split("(", 1)[0].strip()
        if directive not in ("Graphics_Task", "Compute_Task", "End_Task") and not CURTASK_OPEN:
            abort("directive outside task")

        if directive in ("Graphics_Task", "Compute_Task"):
            if CURTASK_OPEN: abort("'%s' opens before previous task '%s' was closed with End_Task." % (line, CURTASK_NAME))
            if len(lineArgs) != 1 or not lineArgs[0]: abort("task header missing name or has extra arguments")
            if lineArgs[0] in TASK_SOURCES:
                abort("duplicate task '%s', first declared at %s" % (lineArgs[0], TASK_SOURCES[lineArgs[0]]))
            CURTASK_NAME = lineArgs[0]
            CURTASK_LOCATION = "%s:%d" % (os.path.basename(fileName), lineIndex)
            TASK_SOURCES[CURTASK_NAME] = CURTASK_LOCATION
            CURTASK_SOURCE = (
                "Generated from definition in %s. DO NOT EDIT HERE!"
                % os.path.basename(fileName)
            )
            CURTASK_IO = []
            CURTASK_CREATE = []
            CURTASK_LIFETIME = {}
            CURTASK_CPU_PROFILE = ""
            CURTASK_GPU_PROFILE = ""
            CURTASK_FUNC = ""
            CURTASK_OPEN = True
            if directive == "Graphics_Task":
                CURTASK_TYPE = "graphics"
            else:
                CURTASK_TYPE = "compute"
        elif directive == "End_Task":
            if lineArgs: abort("End_Task takes no arguments")
            if not CURTASK_OPEN: abort("End_Task without matching Graphics_Task/Compute_Task.")
            declared = [name for t, name, args in CURTASK_CREATE]
            if len(set(declared)) != len(declared):
                abort("duplicate resource declaration")
            for name in CURTASK_LIFETIME:
                if name not in declared:
                    abort("Lifetime requires a resource declared in this task: %s" % name)
            if any(name in declared for t, name, args in CURTASK_IO):
                abort("declare resources before accessing them in a later task")
            generateCurrentTask()
            CURTASK_OPEN = False
        elif directive in IOTYPE_TO_FUNCTIONARG and not directive.startswith("Create_"):
            if not CURTASK_OPEN:
                abort("resource access outside task")
            t = directive
            if not lineArgs or not all(lineArgs) or len(lineArgs) > 3:
                abort("invalid resource access")
            name, args = lineArgs[0], lineArgs[1:]
            if args and args[-1] == "Discard":
                roles = args[:-1]
            else:
                roles = args
            if len(roles) > 1 or (roles and roles[0] not in ACCESS_ROLES):
                abort("expected one access role followed by optional Discard")
            error = getAccessError(t, args)
            if error: abort(error)
            for i, (previous, previousName, previousArgs) in enumerate(CURTASK_IO):
                if previousName != name:
                    continue
                if IOTYPE_TO_ATTACH[previous] != IOTYPE_TO_ATTACH[t]:
                    abort("conflicting resource types")
                if ("Discard" in args or "Discard" in previousArgs) and (t != previous or ("Discard" in args) != ("Discard" in previousArgs)):
                    abort("conflicting discard access")
                merged = previous if previous == t else "ReadWrite_" + t.split("_", 1)[1]
                mergedArgs = [role for role in ACCESS_ROLES if role in args or role in previousArgs]
                if "Discard" in args: mergedArgs.append("Discard")
                error = getAccessError(merged, mergedArgs)
                if error: abort(error)
                CURTASK_IO[i] = (merged, name, mergedArgs)
                break
            else:
                CURTASK_IO.append((t, name, args))
        elif directive == "Lifetime":
            if not CURTASK_OPEN or len(lineArgs) != 2 or lineArgs[1] not in ("Transient", "Persistent", "Imported"):
                abort("Lifetime requires (resource, Transient|Persistent|Imported) inside a task")
            if lineArgs[0] in CURTASK_LIFETIME:
                abort("duplicate Lifetime declaration")
            CURTASK_LIFETIME[lineArgs[0]] = lineArgs[1]
        elif directive == "Create_Buffer":
            if not CURTASK_OPEN or len(lineArgs) != 4 or not all(lineArgs):
                abort("Create_Buffer requires (name, size, format, flags) inside a task")
            CURTASK_CREATE.append(("Create_Buffer", lineArgs[0], lineArgs[1:]))
        elif directive == "Create_TextureFB":
            if not CURTASK_OPEN or len(lineArgs) not in (5, 6) or not all(lineArgs):
                abort("Create_TextureFB requires (name, width, height, format, mips[, flags]) inside a task")
            CURTASK_CREATE.append(("Create_TextureFB", lineArgs[0], lineArgs[1:]))
        elif directive in ("CPU_Profile", "GPU_Profile", "Func"):
            if len(lineArgs) != 1 or not lineArgs[0]:
                abort("%s requires one nonempty argument" % directive)
            if directive == "CPU_Profile":
                if CURTASK_CPU_PROFILE: abort("duplicate CPU_Profile")
                CURTASK_CPU_PROFILE = lineArgs[0]
            elif directive == "GPU_Profile":
                if CURTASK_GPU_PROFILE: abort("duplicate GPU_Profile")
                if lineArgs[0] in GPU_PROFILE_SOURCES:
                    abort("Duplicate GPU_Profile name '%s', first declared at %s" % (lineArgs[0], GPU_PROFILE_SOURCES[lineArgs[0]]))
                GPU_PROFILE_SOURCES[lineArgs[0]] = "%s:%d" % (fileName, lineIndex)
                CURTASK_GPU_PROFILE = lineArgs[0]
            else:
                if CURTASK_FUNC: abort("duplicate Func")
                CURTASK_FUNC = lineArgs[0]
        else:
            abort("unknown directive '%s'" % directive)

    if CURTASK_OPEN: _abort(CURTASK_LOCATION, -1, "missing End_Task at end of file")


# -------------------------------------------------- Main Script -----------------------------------------------------------

for file in glob.glob(sys.argv[1]):
    parseSourceFile(file)

OUTPUT_FILE_BUFFER.append("\n} // namespace vrdg\n")
OUTPUT_FILE_BUFFER.append("\n")
OUTPUT_FILE_BUFFER.append("#include <utility>\n")
OUTPUT_FILE_BUFFER.append("\n")

